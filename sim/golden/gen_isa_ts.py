"""Generate web/src/lib/isa.ts from decode.py so the TypeScript assembler/disassembler and the
Python golden model share one opcode table.

    python -m golden.gen_isa_ts            # rewrite the file
    python -m golden.gen_isa_ts --check    # exit 1 if it is stale (used by pytest/CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

from golden.decode import CSR_NAMES, FORMATS, INSNS, REG_NAMES

OUT = Path(__file__).resolve().parents[2] / "web" / "src" / "lib" / "isa.ts"


def render() -> str:
    rows = "\n".join(
        f'  {{ name: "{d.name}", fmt: "{d.fmt}", mask: 0x{d.mask:08x}, match: 0x{d.match:08x} }},'
        for d in INSNS
    )
    regs = ", ".join(f'"{r}"' for r in REG_NAMES)
    csrs = "\n".join(f'  0x{k:03x}: "{v}",' for k, v in CSR_NAMES.items())
    fmts = " | ".join(f'"{f}"' for f in FORMATS)
    return f"""// GENERATED by sim/golden/gen_isa_ts.py from sim/golden/decode.py - do not edit.
// Regenerate: (cd sim && python -m golden.gen_isa_ts)

export type InsnFormat = {fmts};

export interface InsnDef {{
  name: string;
  fmt: InsnFormat;
  /** An instruction word w matches when (w & mask) === match. */
  mask: number;
  match: number;
}}

export const INSNS: readonly InsnDef[] = [
{rows}
];

/** ABI register names, indexed by register number. */
export const REG_NAMES: readonly string[] = [{regs}];

/** Implemented read-only counter CSRs (Zicntr subset). */
export const CSR_NAMES: Readonly<Record<number, string>> = {{
{csrs}
}};
"""


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run `python -m golden.gen_isa_ts` from sim/", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
